export function formatCtxTokens(n) {
    if (!n) return '0';
    if (n < 1000) return String(n);
    var k = n / 1000;
    return (k >= 100 ? Math.round(k) : (Math.round(k * 10) / 10).toFixed(1).replace(/\.0$/, '')) + 'K';
}
